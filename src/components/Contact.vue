<script setup>
import { ref, onMounted, onBeforeUnmount, nextTick } from 'vue';
import { animate, stagger } from 'animejs';
import emailjs from '@emailjs/browser';

const sectionRef = ref(null);
const formRef = ref(null);

let observer = null;
let hasAnimated = false;
let statusTimeout = null;

const STATUS_DURATION = 10000;

const isSending = ref(false);
const sendStatus = ref('idle');
const statusMessage = ref('');
const statusKey = ref(0);

const EMAILJS_SERVICE_ID = import.meta.env.VITE_EMAILJS_SERVICE_ID;
const EMAILJS_TEMPLATE_ID = import.meta.env.VITE_EMAILJS_TEMPLATE_ID;
const EMAILJS_PUBLIC_KEY = import.meta.env.VITE_EMAILJS_PUBLIC_KEY;

const runAnimation = () => {
  if (hasAnimated) return;
  hasAnimated = true;

  animate('.heading-block', {
    opacity: [0, 1],
    y: [40, 0],
    duration: 900,
    ease: 'outExpo'
  });

  animate('.contact-item', {
    opacity: [0, 1],
    y: [35, 0],
    duration: 900,
    delay: stagger(120, { start: 150 }),
    ease: 'outExpo'
  });

  animate('.form-panel', {
    opacity: [0, 1],
    y: [50, 0],
    duration: 1000,
    delay: 250,
    ease: 'outExpo'
  });
};

const showStatus = (type, message) => {
  if (statusTimeout) clearTimeout(statusTimeout);

  sendStatus.value = type;
  statusMessage.value = message;
  statusKey.value += 1;

  statusTimeout = setTimeout(() => {
    sendStatus.value = 'idle';
    statusMessage.value = '';
  }, STATUS_DURATION);
};

const sendEmail = async () => {
  if (!formRef.value || isSending.value) return;

  isSending.value = true;
  sendStatus.value = 'idle';
  statusMessage.value = '';

  try {
    await emailjs.sendForm(
      EMAILJS_SERVICE_ID,
      EMAILJS_TEMPLATE_ID,
      formRef.value,
      { publicKey: EMAILJS_PUBLIC_KEY }
    );

    formRef.value.reset();
    showStatus('success', 'Message sent successfully!');
  } catch (error) {
    console.error('FAILED...', error);
    showStatus('error', 'Failed to send message. Try again.');
  } finally {
    isSending.value = false;
  }
};

onMounted(async () => {
  await nextTick();

  observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          runAnimation();
          observer.disconnect();
        }
      });
    },
    {
      threshold: 0.2,
      rootMargin: '0px 0px -80px 0px'
    }
  );

  if (sectionRef.value) {
    observer.observe(sectionRef.value);
  }
});

onBeforeUnmount(() => {
  if (observer) observer.disconnect();
  if (statusTimeout) clearTimeout(statusTimeout);
});
</script>


